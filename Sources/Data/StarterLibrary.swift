import Foundation
import GRDB

/// The bundled Mood Starter library as an SQLite database ("starter DB") assembled from immutable
/// Jamendo shards: track metadata, native 128-D CLAP embeddings and tempo/key/energy. Nothing else: blends
/// are planned on the device from the audio itself (MixDeckPlayer), and the tempo here is all
/// the planner takes from it (a hint it searches ±1% around).
///
/// The app opens it read-only from the bundle and merges its rows into the library in one
/// transaction (`LibraryStore.mergeStarterLibrary`). The iPhone and the Mac ship the same
/// `starter.sqlite`, a build input fetched by `scripts/fetch-starter.sh`, not committed.
public final class StarterLibrary: Sendable {
    /// 4: native int4/128-D CLAP rollout. Rows carry canonical little-endian Float32 embeddings
    /// and a transition profile generated by the immutable shard pipeline. Earlier starter
    /// formats are deliberately not accepted: their embeddings belong to retired model spaces.
    public static let formatVersion = 4
    public static let resourceNames = ["starter"]

    /// The bundled starter DB, or nil when the build doesn't carry one.
    public static let shared: StarterLibrary? = {
        guard let url = bundledURL else { return nil }
        return try? StarterLibrary(url: url)
    }()

    /// The app bundle's starter DB. Each app carries only its own (project.yml); the shared
    /// package bundle deliberately carries none, or every app and extension would embed both.
    /// `swift test` and BuiltInAnalyzer have no app bundle and read the fetched copy in the
    /// source tree (`Resources/Starter/`, `make starter`).
    public static var bundledURL: URL? {
        for name in resourceNames {
            if let url = Bundle.main.url(forResource: name, withExtension: "sqlite") { return url }
        }
        #if SWIFT_PACKAGE
        let sourceTree = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Resources/Starter", isDirectory: true)
        for name in resourceNames {
            let url = sourceTree.appendingPathComponent("\(name).sqlite")
            if FileManager.default.fileExists(atPath: url.path) { return url }
        }
        #endif
        return nil
    }

    private let dbQueue: DatabaseQueue
    /// Content identity of this starter DB (from `starter_meta`), used to re-merge after an update.
    public let contentVersion: String

    public init(url: URL) throws {
        var config = Configuration()
        config.readonly = true
        config.label = "StarterLibrary"
        dbQueue = try DatabaseQueue(path: url.path, configuration: config)
        let format = try dbQueue.read { db in
            try String.fetchOne(db, sql: "SELECT value FROM starter_meta WHERE key = 'format_version'")
        }
        guard format == String(Self.formatVersion) else {
            throw StarterLibraryError.unsupportedFormat(format ?? "missing")
        }
        contentVersion = try dbQueue.read { db in
            try String.fetchOne(db, sql: "SELECT value FROM starter_meta WHERE key = 'content_version'")
        } ?? "unknown"
    }

    public func meta(_ key: String) throws -> String? {
        try dbQueue.read { db in
            try String.fetchOne(db, sql: "SELECT value FROM starter_meta WHERE key = ?", arguments: [key])
        }
    }

    /// Every track, with the native 128-D embedding converted to the app's compact in-memory
    /// quantized representation.
    public func tracks() throws -> [BuiltInMoodTrack] {
        try storedTracks()
    }

    private func storedTracks() throws -> [BuiltInMoodTrack] {
        try dbQueue.read { db in
            try Row.fetchAll(db, sql: """
                SELECT id, title, artist, genre, license, duration, stream_url,
                       bpm, camelot, energy, emb_dimensions, emb_vector, transition_profile_json
                FROM starter_track ORDER BY id
                """).map { row in
                let dimensions: Int = row["emb_dimensions"]
                let vector: Data = row["emb_vector"]
                let floats = try Self.decodeNativeVector(vector, dimensions: dimensions)
                let (quantized, scale) = EmbeddingProjection.quantize(floats)
                let profile: TransitionProfile = try Self.decodeProfile(row["transition_profile_json"])
                BuiltInMoodTrack(
                    id: row["id"], title: row["title"], artist: row["artist"], genre: row["genre"],
                    license: row["license"], licenseURL: nil, durationSec: row["duration"],
                    streamURL: row["stream_url"], artworkURL: nil,
                    dimensions: dimensions, scale: scale, quantizedVector: quantized,
                    bpm: profile.bpm ?? row["bpm"], key: profile.key ?? row["camelot"],
                    energy: profile.energy ?? row["energy"], analysisScopeSeconds: profile.analysisScopeSeconds)
            }
        }
    }

    private struct TransitionProfile: Decodable {
        let bpm: Double?
        let key: String?
        let energy: Double?
        let analysisScopeSeconds: Double?
    }

    private static func decodeProfile(_ json: String) throws -> TransitionProfile {
        guard let data = json.data(using: .utf8) else { throw StarterLibraryError.invalidRow("transition profile") }
        return try JSONDecoder().decode(TransitionProfile.self, from: data)
    }

    private static func decodeNativeVector(_ data: Data, dimensions: Int) throws -> [Float] {
        guard dimensions == 128, data.count == dimensions * MemoryLayout<UInt32>.size else {
            throw StarterLibraryError.invalidRow("embedding dimensions")
        }
        let bytes: [UInt8] = Array(data)
        var vector: [Float] = []
        vector.reserveCapacity(dimensions)
        for offset in stride(from: 0, to: bytes.count, by: 4) {
            let low = UInt32(bytes[offset])
            let high = UInt32(bytes[offset + 1]) << 8
            let upper = UInt32(bytes[offset + 2]) << 16
            let top = UInt32(bytes[offset + 3]) << 24
            vector.append(Float(bitPattern: low | high | upper | top))
        }
        guard vector.allSatisfy({ $0.isFinite }) else { throw StarterLibraryError.invalidRow("non-finite embedding") }
        return vector
    }
}

public enum StarterLibraryError: Error, Equatable {
    case unsupportedFormat(String)
    case invalidRow(String)
}

/// Test/developer helper for emitting the same native starter v4 schema that the shard assembler emits.
public enum StarterLibraryWriter {
    public static func create(at url: URL, tracks: [BuiltInMoodTrack], meta: [String: String],
                              embeddingDimensions: Int? = nil) throws {
        _ = embeddingDimensions // Native v4 deliberately does not project embeddings.
        try? FileManager.default.removeItem(at: url)
        var config = Configuration()
        config.journalMode = .default
        let queue = try DatabaseQueue(path: url.path, configuration: config)
        try queue.write { db in
            try db.execute(sql: """
                CREATE TABLE starter_meta (key TEXT PRIMARY KEY NOT NULL, value TEXT NOT NULL);
                CREATE TABLE starter_batch (batch_id TEXT PRIMARY KEY NOT NULL, batch_manifest_sha256 TEXT NOT NULL,
                    shard_logical_digest TEXT NOT NULL, track_count INTEGER NOT NULL);
                CREATE TABLE starter_track (
                    provider TEXT NOT NULL, provider_track_id TEXT NOT NULL, id TEXT NOT NULL UNIQUE,
                    batch_id TEXT NOT NULL REFERENCES starter_batch(batch_id), source_revision TEXT NOT NULL,
                    title TEXT NOT NULL, artist TEXT NOT NULL, genre TEXT NOT NULL, license TEXT NOT NULL,
                    duration REAL NOT NULL, stream_url TEXT NOT NULL UNIQUE, bpm REAL, camelot TEXT, energy REAL,
                    emb_dimensions INTEGER NOT NULL, emb_vector BLOB NOT NULL,
                    transition_profile_json TEXT NOT NULL, payload_sha256 TEXT NOT NULL,
                    PRIMARY KEY (provider, provider_track_id));
                """)
            try db.execute(sql: "INSERT INTO starter_batch VALUES (?, ?, ?, ?)",
                           arguments: ["test", "test", "test", tracks.count])
            for track in tracks {
                let vector = EmbeddingProjection.dequantize(track.quantizedVector, scale: track.scale)
                let profile = try JSONEncoder().encode(TransitionProfile(bpm: track.bpm, key: track.key,
                                                                           energy: track.energy,
                                                                           analysisScopeSeconds: track.analysisScopeSeconds))
                try db.execute(sql: """
                    INSERT INTO starter_track VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, arguments: [
                        "test", track.id, track.id, "test", "test", track.title, track.artist, track.genre,
                        track.license, track.durationSec, track.streamURL, track.bpm, track.key, track.energy,
                        vector.count, nativeVectorData(vector), String(decoding: profile, as: UTF8.self), track.id])
            }
            var allMeta = meta
            allMeta["format_version"] = String(StarterLibrary.formatVersion)
            for (key, value) in allMeta {
                try db.execute(sql: "INSERT INTO starter_meta VALUES (?, ?)", arguments: [key, value])
            }
        }
        try queue.vacuum()
    }

    private struct TransitionProfile: Codable {
        let bpm: Double?
        let key: String?
        let energy: Double?
        let analysisScopeSeconds: Double?
    }

    private static func nativeVectorData(_ vector: [Float]) -> Data {
        var bytes: [UInt8] = []
        bytes.reserveCapacity(vector.count * 4)
        for value in vector {
            let word = value.bitPattern
            bytes.append(UInt8(truncatingIfNeeded: word))
            bytes.append(UInt8(truncatingIfNeeded: word >> 8))
            bytes.append(UInt8(truncatingIfNeeded: word >> 16))
            bytes.append(UInt8(truncatingIfNeeded: word >> 24))
        }
        return Data(bytes)
    }
}
