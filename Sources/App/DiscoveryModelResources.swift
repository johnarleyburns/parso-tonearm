/// Resolves the converted CLAP audio + text encoders and their bundled
/// sidecars for the Discovery indexing/search pipeline, the same way the DJ
/// semantic stack delivers Core ML resources (IMPLEMENT_CLAP_PLAN.md §8):
///
///  - the ~123 MB `CLAPAudioEncoder` package is an On-Demand Resource, tag
///    `clap-audio`; the ~221 MB `CLAPTextEncoder` package is ODR tag
///    `clap-text` — both real CoreML packages of comparable size, not a
///    small sidecar (`Config/models-odr.yml`, generated by
///    `scripts/generate-project.sh` from what is on the build host). Xcode
///    compiles each `.mlpackage` to a `.mlmodelc` inside the asset pack;
///    ODR content is mounted into the main bundle's resource directory once
///    `beginAccessingResources` succeeds. Combined, this is a ~344 MB
///    one-time fetch — on a slow connection, or if iOS is deferring it
///    pending Wi-Fi (Settings → Cellular → per-app "Automatic Downloads"),
///    genuinely taking a long time looks identical to being stuck; there is
///    no public API to tell "slow" apart from "iOS is waiting for Wi-Fi"
///    for On-Demand Resources.
///  - `mel_filterbank_slaney_64.bin` (audio frontend) and the RoBERTa
///    `vocab.json` / `merges.txt` (text tokenizer) ship bundled in
///    `Resources/CLAP/`.
///
/// When the ODR pack has not been fetched (or the tag is absent from a build
/// with no converted package on the host), `currentResources()` returns
/// `.unavailable` and every index job parks at `waitingForModel` — never a
/// fabricated embedding (plan §8).
final class DiscoveryModelResources: @unchecked Sendable {
    static let shared = DiscoveryModelResources()

    /// Must match the tags in `Config/models-odr.yml` / `ModelTag`.
    private static let audioTag = "clap-audio"
    private static let textTag = "clap-text"

    private let audioRequest = NSBundleResourceRequest(tags: [DiscoveryModelResources.audioTag])
    private let textRequest = NSBundleResourceRequest(tags: [DiscoveryModelResources.textTag])
    private let lock = NSLock()
    private var didBeginAccessing = false
    private var lastError: String?
    private var retryWorkItem: DispatchWorkItem?
    private var retryDelay: TimeInterval = 5

    /// The most recent `beginAccessingResources` failure, if any — surfaced
    /// through diagnostics and the status UI so a stalled/failed ODR fetch
    /// (e.g. `NSBundleResourceRequestLowDiskSpaceKey`,
    /// `NSBundleResourceRequestUnknownResourceIdentifierError`, or a plain
    /// network error) is never invisible (CLAUDE.md "no silent/magic
    /// background work"). `nil` once a retry begins or resources resolve.
    func currentDownloadError() -> String? {
        lock.lock()
        defer { lock.unlock() }
        return lastError
    }

    /// Ask iOS to make the `clap-audio` ODR pack available. Best-effort;
    /// a failure (no such tag, no network on first fetch, low disk space)
    /// is captured in `currentDownloadError()` — never just an `NSLog` line
    /// invisible to both the user and support — and retried with backoff
    /// rather than left to park at `waitingForModel` forever (FR-SEM-6 /
    /// §8: honest, but not silently stuck).
    func beginAccessing() {
        lock.lock()
        let already = didBeginAccessing
        didBeginAccessing = true
        lock.unlock()
        guard !already else { return }
        startRequests()
    }

    private func startRequests() {
        for (tag, request) in [(Self.audioTag, audioRequest), (Self.textTag, textRequest)] {
            request.loadingPriority = NSBundleResourceRequestLoadingPriorityUrgent
            request.beginAccessingResources { [weak self] error in
                guard let self else { return }
                if let error {
                    let message = "\(tag): \((error as NSError).localizedDescription) (code \((error as NSError).code))"
                    NSLog("[Discovery] ODR not available: \(message)")
                    self.lock.lock()
                    self.lastError = message
                    let delay = self.retryDelay
                    self.retryDelay = min(self.retryDelay * 2, 300)
                    self.lock.unlock()
                    self.scheduleRetry(after: delay)
                } else {
                    self.lock.lock()
                    self.lastError = nil
                    self.retryDelay = 5
                    self.lock.unlock()
                }
            }
        }
    }

    /// A failed `beginAccessingResources` call does not retry on its own —
    /// without this, a transient failure (e.g. no network at launch) would
    /// leave the app parked at `waitingForModel` indefinitely even once
    /// connectivity returns, with no user action able to fix it (the "0%
    /// downloaded... then it disappeared" report this guards against).
    private func scheduleRetry(after delay: TimeInterval) {
        lock.lock()
        retryWorkItem?.cancel()
        let item = DispatchWorkItem { [weak self] in self?.startRequests() }
        retryWorkItem = item
        lock.unlock()
        DispatchQueue.main.asyncAfter(deadline: .now() + delay, execute: item)
    }

    /// Synchronously resolve whatever is on disk right now — safe to hand to
    /// `ModelManager`'s `@Sendable () -> Resources` provider. Passes
    /// `Bundle.main` so ODR-mounted content actually resolves — its
    /// on-disk location is a hashed, unpredictable asset-pack directory
    /// (see `ModelResourceLocator.bundle`'s doc), not a guessable child of
    /// `resourceURL`; `searchDirectories` alone was never sufficient for
    /// real On-Demand Resource content, only for the dev-checkout/test
    /// case where resources sit in a plain folder.
    func currentResources() -> ModelManager.Resources {
        var directories: [URL] = []
        if let resourceURL = Bundle.main.resourceURL {
            directories.append(resourceURL)
        }
        return ModelResourceLocator(searchDirectories: directories, bundle: Bundle.main).resolve()
    }

    /// Real bytes off `NSBundleResourceRequest.progress` for both tags —
    /// never a fabricated fraction (CLAUDE.md "no silent/magic background
    /// work": a `waitingForModel` state with no size is indistinguishable
    /// from stuck). `nil` only before either tag has reported any byte
    /// count at all. The actual summing happens in
    /// `ModelDownloadProgress.aggregate(_:)` (`Sources/Discovery/`) — kept
    /// out of this Xcode-only file specifically so it's covered by
    /// `swift test`; this method's only job is turning the two live
    /// `NSBundleResourceRequest.progress` objects into plain samples.
    func currentDownloadProgress() -> ModelDownloadProgress? {
        ModelDownloadProgress.aggregate(perTagSamples().map(\.1))
    }

    /// Per-tag byte counts for the diagnostics export — the combined
    /// `currentDownloadProgress()` number can't tell "one tag finished
    /// while the other is genuinely stuck at zero" apart from "both
    /// progressing normally" (real report: a small `clap-text` finished
    /// while the ~137 MB `clap-audio` never reported any bytes at all,
    /// which the combined number alone rendered as a nonsensical "0 of 0
    /// MB (100%)"). This is what lets a diagnostics export say exactly
    /// which tag is the one not moving, instead of one ambiguous blend.
    func currentPerTagDebugSummary() -> String {
        perTagSamples()
            .map { tag, sample in
                let state = sample.isFinished ? "finished" : (sample.totalBytes > 0 ? "in progress" : "not started")
                return "\(tag): \(sample.completedBytes)/\(sample.totalBytes) bytes (\(state))"
            }
            .joined(separator: "; ")
    }

    private func perTagSamples() -> [(String, ModelDownloadProgress.RequestSample)] {
        [(Self.audioTag, audioRequest), (Self.textTag, textRequest)].map { tag, request in
            (tag, ModelDownloadProgress.RequestSample(
                completedBytes: request.progress.completedUnitCount,
                totalBytes: request.progress.totalUnitCount,
                isFinished: request.progress.isFinished))
        }
    }
}
#endif
