#if !os(watchOS)
import Foundation
import ParsoAudioAnalysis
import StarterGeneratorSupport
import TonearmCore

// Dev-only offline tool: regenerates Sources/Domain/Mix/StarterBlendRuntimeData.swift from real
// drop/bass-exit structure instead of bassSwap-only arithmetic. Input is a source-controlled JSON
// file (tools/starter-blends/structure-input.json) carrying exactly the fixed blend/edge sequence
// (blendID, edge, outgoing/incoming track IDs — curation decisions, never re-derived) plus each
// track's StarterTrackFacts (bpm/beatPeriod/beatPhase/durationSeconds/rmsDB, already measured from
// the real audio by the original curation). This tool adds the one thing that was still arithmetic
// fiction: it downloads each track's full audio from Jamendo, runs ParsoAudioAnalysis.DropDetector
// against a constant-tempo beat grid built from the known bpm/beatPhase, and asks
// DropAwareEdgePlanner for a real doubleDrop/bassSwap/phraseCut edge before falling back to
// CatalogEdgePlanner's plain bassSwap (same algorithm StarterBlendRuntimeData.swift ships today).
//
// Usage: swift run StarterBlendEdgePlanner <structure-input.json> <output.swift>

@main
struct StarterBlendEdgePlanner {
    struct TrackInput: Decodable, Sendable {
        let id: String
        let bpm: Double
        let beatPeriod: Double
        let beatPhase: Double
        let durationSeconds: Double
        let rmsDB: Double
    }
    struct EdgeInput: Decodable {
        let blendID: String
        let edge: Int
        let outgoingTrackID: String
        let incomingTrackID: String
    }
    struct Input: Decodable {
        let tracks: [TrackInput]
        let edges: [EdgeInput]
    }

    static func main() async {
        let args = CommandLine.arguments
        guard args.count == 3 else {
            FileHandle.standardError.write("usage: StarterBlendEdgePlanner <structure-input.json> <output.swift>\n".data(using: .utf8)!)
            exit(1)
        }
        let inputURL = URL(fileURLWithPath: args[1])
        let outputURL = URL(fileURLWithPath: args[2])
        guard let data = try? Data(contentsOf: inputURL),
              let input = try? JSONDecoder().decode(Input.self, from: data) else {
            FileHandle.standardError.write("cannot read \(inputURL.path)\n".data(using: .utf8)!)
            exit(1)
        }
        say("\(input.tracks.count) tracks, \(input.edges.count) edges")

        var facts: [String: StarterTrackFacts] = [:]
        var structures: [String: DropAwareTrackStructure] = [:]
        for track in input.tracks {
            facts[track.id] = StarterTrackFacts(
                id: track.id, durationSeconds: track.durationSeconds, bpm: track.bpm,
                beatPeriod: track.beatPeriod, beatPhase: track.beatPhase, rmsDB: track.rmsDB)
            guard let structure = await analyzeStructure(track) else {
                say("  \(track.id): structure analysis unavailable; will fall back to bassSwap")
                continue
            }
            structures[track.id] = structure
            say("  \(track.id): \(structure.drops.count) drop(s), \(structure.exits.count) exit(s), " +
                "barPhase \(structure.barPhase), phrasePhase \(structure.phrasePhase)")
        }

        var styleCounts: [String: Int] = [:]
        var lines: [String] = []
        for e in input.edges {
            guard let outgoingFacts = facts[e.outgoingTrackID], let incomingFacts = facts[e.incomingTrackID] else {
                say("MISSING FACTS for edge \(e.blendID)#\(e.edge); skipping")
                continue
            }
            var plan: BlendEdgePlan?
            if let outStruct = structures[e.outgoingTrackID], let inStruct = structures[e.incomingTrackID] {
                plan = DropAwareEdgePlanner.plan(
                    blendID: e.blendID, edge: e.edge, outgoing: outgoingFacts, outgoingStructure: outStruct,
                    incoming: incomingFacts, incomingStructure: inStruct)
            }
            if plan == nil {
                plan = CatalogEdgePlanner.plan(
                    blendID: e.blendID, edge: e.edge, outgoing: outgoingFacts, incoming: incomingFacts)
            }
            guard let plan else {
                say("NO PLAN for edge \(e.blendID)#\(e.edge) (\(e.outgoingTrackID) -> \(e.incomingTrackID))")
                continue
            }
            styleCounts[plan.style.rawValue, default: 0] += 1
            lines.append("        " + emit(plan) + ",")
        }
        say("styles: \(styleCounts)")

        let out = """
        // Generated by Sources/Tools/StarterBlendEdgePlanner from tools/starter-blends/structure-input.json
        // (the fixed blend/edge sequence and curated track timing facts) plus real drop/bass-exit structure
        // detected by ParsoAudioAnalysis.DropDetector against each track's full downloaded audio
        // (DropAwareEdgePlanner), with CatalogEdgePlanner's plain bassSwap as the fallback where no usable
        // structure was found. Do not edit by hand.
        import Foundation

        enum StarterBlendRuntimeData {
            static let edges: [BlendEdgePlan] = [
        \(lines.joined(separator: "\n"))
            ]
        }
        """
        do {
            try out.write(to: outputURL, atomically: true, encoding: .utf8)
            say("wrote \(outputURL.path)")
        } catch {
            FileHandle.standardError.write("write failed: \(error)\n".data(using: .utf8)!)
            exit(1)
        }
    }

    static func analyzeStructure(_ track: TrackInput) async -> DropAwareTrackStructure? {
        let temp = FileManager.default.temporaryDirectory
            .appendingPathComponent("starter-blend-edge-\(track.id)-\(UUID().uuidString).mp3")
        defer { try? FileManager.default.removeItem(at: temp) }
        let url = URL(string: "https://mp3d.jamendo.com/download/track/\(track.id)/mp32/")!
        var downloaded = false
        for attempt in 0..<3 where !downloaded {
            downloaded = await curl(url, to: temp)
            if !downloaded && attempt < 2 { try? await Task.sleep(for: .seconds(2)) }
        }
        guard downloaded else { say("  \(track.id): download failed"); return nil }

        return await Task.detached(priority: .utility) { () -> DropAwareTrackStructure? in
            let reader = WindowedAudioReader()
            guard let pcm = try? reader.readWindow(url: temp, startSeconds: 0, windowSeconds: track.durationSeconds),
                  !pcm.isEmpty else { return nil }
            let audio = AnalysisAudio(sampleRate: reader.targetSampleRate, channels: [pcm])
            var beatSamples: [Int64] = []
            var t = track.beatPhase
            while t < track.durationSeconds {
                let sample = Int64((t * reader.targetSampleRate).rounded())
                if sample >= 0, sample < Int64(pcm.count) { beatSamples.append(sample) }
                t += track.beatPeriod
            }
            guard beatSamples.count > 64 else { return nil }
            let (drops, exits, bassLevelsDB) = DropDetector.dropsAndExits(audio, beatSamples: beatSamples)
            return DropAwareTrackStructure.detect(
                rawDrops: drops, rawExits: exits, beatCount: beatSamples.count, bassLevelsDB: bassLevelsDB)
        }.value
    }

    static func emit(_ p: BlendEdgePlan) -> String {
        let style: String
        switch p.style {
        case .bassSwap: style = ".bassSwap"
        case .doubleDrop: style = ".doubleDrop"
        case .phraseCut: style = ".phraseCut"
        }
        var args = [
            "blendID: \"\(p.blendID)\"", "edge: \(p.edge)", "outgoingTrackID: \"\(p.outgoingTrackID)\"",
            "incomingTrackID: \"\(p.incomingTrackID)\"", "style: \(style)", "tempo: \(p.tempo)",
            "overlapBeats: \(p.overlapBeats)"
        ]
        if let v = p.incomingGain { args.append("incomingGain: \(v)") }
        if let v = p.outgoingSwapBeat { args.append("outgoingSwapBeat: \(v)") }
        if let v = p.incomingSwapBeat { args.append("incomingSwapBeat: \(v)") }
        if let v = p.blendStartSeconds { args.append("blendStartSeconds: \(v)") }
        if let v = p.swapSeconds { args.append("swapSeconds: \(v)") }
        if let v = p.blendEndSeconds { args.append("blendEndSeconds: \(v)") }
        if let v = p.incomingOffsetSeconds { args.append("incomingOffsetSeconds: \(v)") }
        if let v = p.outgoingStartSeconds { args.append("outgoingStartSeconds: \(v)") }
        if let v = p.incomingStartSeconds { args.append("incomingStartSeconds: \(v)") }
        return "BlendEdgePlan(" + args.joined(separator: ", ") + ")"
    }

    static func say(_ line: String) {
        FileHandle.standardOutput.write((line + "\n").data(using: .utf8)!)
    }

    static func curl(_ url: URL, to file: URL) async -> Bool {
        await withCheckedContinuation { continuation in
            let process = Process()
            process.executableURL = URL(fileURLWithPath: "/usr/bin/curl")
            process.arguments = ["-sfL", "--max-time", "90", "-o", file.path, url.absoluteString]
            process.terminationHandler = { finished in
                continuation.resume(returning: finished.terminationStatus == 0)
            }
            do { try process.run() } catch { continuation.resume(returning: false) }
        }
    }
}
