#!/bin/bash
# Generate Tonearm.xcodeproj — `make project`.
#
# This wraps `xcodegen generate` with exactly one decision:
# is that converted Core ML package on this machine?
#
#   Resources/Models/DemucsStems.mlpackage       present → optional ODR tag
#                                                         demucs-stems
#                                                         (Config/models-odr.yml)
#   absent → not in the project; the feature reports itself unavailable
#   (§36.5, FR-SEM-6).
#
# Env hooks (tests): TONEARM_REPO_ROOT overrides the repo root;
# TONEARM_GENERATE_OVERLAYS_ONLY=1 writes the overlay and skips xcodegen.
#
# WHY THIS EXISTS. The package is not in the repository. Demucs is
# 210 MB of FP32 weights, gitignored like every other build product (plan
# dj-stems-model S6). So a checkout does not have it until something fetches
# it — and a clean checkout is what CI builds from.
#
# Listing a missing package unconditionally in project.yml made `xcodegen
# generate` fail outright ("Target Tonearm has a missing source directory");
# marking it `optional: true` got past validation and then failed the build
# instead, copying a file that is not there into the asset pack:
#
#   CpResource .../demucs-stems-<hash>.assetpack/DemucsStems.mlpackage
#   ** BUILD FAILED **
#
# Either way the TestFlight job dies before it archives, so the first push would
# have produced no build at all. The overlay this script writes is the fix: the
# entry exists when the directory does.
#
# It is safe to run at any time and safe to run in CI: the overlay is rewritten
# from the filesystem on every run, so an overlay committed by accident cannot
# leak into a build that has no model to back it.

set -euo pipefail

cd "${TONEARM_REPO_ROOT:-$(git rev-parse --show-toplevel)}"

OVERLAY="Config/models-odr.yml"

# Optional packages: package directory : ODR resource tag
OPTIONAL_ODR=(
  "DemucsStems.mlpackage:demucs-stems"
)

present=()
absent=()
for entry in "${OPTIONAL_ODR[@]}"; do
  dir="${entry%%:*}"
  if [[ -d "Resources/Models/$dir" ]]; then
    present+=("$entry")
  else
    absent+=("$dir")
  fi
done

mkdir -p Config

{
  echo "# GENERATED by scripts/generate-project.sh — do not edit, and do not"
  echo "# commit: it is written from which optional model packages are on THIS"
  echo "# machine. Only Demucs is On-Demand; a missing one is the honest"
  echo "# absence path (§36.5, FR-SEM-6): stem faders disabled."
  if [[ ${#present[@]} -eq 0 ]]; then
    echo "#"
    echo "# No optional model packages on this machine, so this overlay is a no-op."
    echo "targets: {}"
  else
    echo "targets:"
    echo "  Tonearm:"
    echo "    sources:"
    for entry in "${present[@]}"; do
      dir="${entry%%:*}"
      tag="${entry##*:}"
      echo "      - path: Resources/Models/$dir"
      echo "        type: folder"
      echo "        buildPhase: resources"
      echo "        resourceTags:"
      echo "          - $tag"
    done
  fi
} > "$OVERLAY"

if [[ ${#present[@]} -gt 0 ]]; then
  echo "==> models: optional ODR in this project — ${present[*]%%:*}"
fi
if [[ ${#absent[@]} -gt 0 ]]; then
  echo "==> models: optional absent, so their ODR tags are not in this project — ${absent[*]}"
fi

if [[ "${TONEARM_GENERATE_OVERLAYS_ONLY:-0}" == 1 ]]; then
  exit 0
fi

# Cloud-drive OAuth client IDs, generated as a real Swift source file rather than read from
# Info.plist at runtime. See OAuthClientConfiguration.swift for why: Info.plist's $(VAR)
# build-setting substitution was a red herring chased through several fix attempts (a shared
# dict, a flat key, pre-declaring the build setting, generation- vs. build-time checks) before
# the real cause surfaced — the actual GitHub Actions secrets for Dropbox/Google Drive had been
# silently stored truncated to 1 character each, from an earlier `gh secret set --body -` call
# piped through printf. Re-set correctly via `gh secret set -f` (an env-file, no piping) and
# confirmed by instrumenting this exact script with stderr debug prints of each resolved value's
# length at generation time. Kept as plain Python (not bash/sed) regardless: simpler to reason
# about and no less portable between the macOS and Linux runners this repo builds on.
#
# Deliberately AFTER the overlay-only early exit above, not before: TONEARM_GENERATE_OVERLAYS_ONLY=1
# is used to exercise this script against a minimal, isolated
# temp fixture containing only Resources/Models/* — no Sources/ tree and no Config/Secrets.xcconfig
# at all. Writing this file unconditionally earlier crashed every one of those tests that reaches
# this point (confirmed by reproducing locally) with a plain "No such file or directory", since
# Sources/Features/Ingest/ doesn't exist in that fixture. This block must only run on the real
# build path, the same one that's about to call xcodegen generate below.
python3 -I - <<'PYEOF'
import os
import re

def xcconfig_value(key, path="Config/Secrets.xcconfig"):
    try:
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()
    except FileNotFoundError:
        return ""
    value = ""
    pattern = re.compile(r"^" + re.escape(key) + r"\s*=\s*(.*?)\s*$")
    for line in lines:
        m = pattern.match(line)
        if m:
            value = m.group(1)
    return value

def swift_literal(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

fields = [
    ("dropboxClientID", "TONEARM_DROPBOX_CLIENT_ID"),
    ("googleDriveClientID", "TONEARM_GOOGLE_DRIVE_CLIENT_ID"),
    ("oneDriveClientID", "TONEARM_ONEDRIVE_CLIENT_ID"),
    ("pCloudClientID", "TONEARM_PCLOUD_CLIENT_ID"),
    ("pCloudClientSecret", "TONEARM_PCLOUD_CLIENT_SECRET"),
    ("boxClientID", "TONEARM_BOX_CLIENT_ID"),
    ("boxClientSecret", "TONEARM_BOX_CLIENT_SECRET"),
    ("yandexClientID", "TONEARM_YANDEX_CLIENT_ID"),
    ("yandexClientSecret", "TONEARM_YANDEX_CLIENT_SECRET"),
]

os.makedirs("Sources/Features/Ingest", exist_ok=True)
with open("Sources/Features/Ingest/GeneratedOAuthCredentials.swift", "w", encoding="utf-8") as out:
    out.write("// GENERATED by scripts/generate-project.sh from Config/Secrets.xcconfig — do not edit,\n")
    out.write("// and do not commit (see .gitignore).\n")
    out.write("enum GeneratedOAuthCredentials {\n")
    for swift_name, xcconfig_key in fields:
        out.write(f"    static let {swift_name} = {swift_literal(xcconfig_value(xcconfig_key))}\n")
    out.write("}\n")
PYEOF

xcodegen generate
