#!/bin/bash
# Generate Tonearm.xcodeproj — `make project`.
#
# This wraps `xcodegen generate` with exactly one decision, taken per model:
# is that converted Core ML package on this machine?
#
#   Resources/Models/CLAPAudioEncoder.mlpackage  present → bundled in the app
#   Resources/Models/CLAPTextEncoder.mlpackage            (Config/models-bundled.yml,
#                                                         no resourceTags)
#   Resources/Models/DemucsStems.mlpackage       present → optional ODR tag
#                                                         demucs-stems
#                                                         (Config/models-odr.yml)
#   absent → not in the project; the feature reports itself unavailable
#   (§36.5, FR-SEM-6). REQUIRE_BUNDLED_CLAP=1 (TestFlight/archive) instead
#   fails before XcodeGen if either CLAP package is missing.
#
# Env hooks (tests): TONEARM_REPO_ROOT overrides the repo root;
# TONEARM_GENERATE_OVERLAYS_ONLY=1 writes the overlays and skips xcodegen.
#
# WHY THIS EXISTS. None of the three packages is in the repository. Demucs is
# 210 MB of FP32 weights, gitignored like every other build product (plan
# dj-stems-model S6); the two CLAP encoders were committed until 2026-08-17,
# when GitHub rejected the first push of the DJ work for exceeding its 100 MB
# file limit, and they became release assets (Config/models.lock,
# scripts/fetch-models.sh). So a checkout does not have them until something
# fetches them — and a clean checkout is what CI builds from.
#
# Listing a missing package unconditionally in project.yml made `xcodegen
# generate` fail outright ("Target Tonearm has a missing source directory");
# marking it `optional: true` got past validation and then failed the build
# instead, copying a file that is not there into the asset pack:
#
#   CpResource .../demucs-stems-<hash>.assetpack/DemucsStems.mlpackage
#   ** BUILD FAILED **
#
# Either way the TestFlight job dies before it archives, so the first push would
# have produced no build at all. The overlay this script writes is the fix: the
# entry exists when the directory does.
#
# It is safe to run at any time and safe to run in CI: the overlay is rewritten
# from the filesystem on every run, so an overlay committed by accident cannot
# leak into a build that has no model to back it.

set -euo pipefail

cd "${TONEARM_REPO_ROOT:-$(git rev-parse --show-toplevel)}"

OVERLAY="Config/models-odr.yml"
BUNDLED_OVERLAY="Config/models-bundled.yml"

# Required CLAP encoders: compiled into the app bundle, never ODR.
BUNDLED_CLAP=(
  "CLAPAudioEncoder.mlpackage"
  "CLAPTextEncoder.mlpackage"
)
# Optional packages: package directory : ODR resource tag
OPTIONAL_ODR=(
  "DemucsStems.mlpackage:demucs-stems"
)

missing_clap=()
present_clap=()
for package in "${BUNDLED_CLAP[@]}"; do
  if [[ -d "Resources/Models/$package" ]]; then
    present_clap+=("$package")
  else
    missing_clap+=("$package")
  fi
done

if [[ "${REQUIRE_BUNDLED_CLAP:-0}" == 1 && ${#missing_clap[@]} -gt 0 ]]; then
  printf 'Required bundled CLAP package missing: %s\n' "${missing_clap[@]}" >&2
  printf 'Run make models; verify Config/models.lock adoption.\n' >&2
  exit 1
fi

present=()
absent=()
for entry in "${OPTIONAL_ODR[@]}"; do
  dir="${entry%%:*}"
  if [[ -d "Resources/Models/$dir" ]]; then
    present+=("$entry")
  else
    absent+=("$dir")
  fi
done

mkdir -p Config

{
  echo "# GENERATED by scripts/generate-project.sh — do not edit, and do not"
  echo "# commit: it is written from which CLAP packages are on THIS machine."
  echo "#"
  echo "# CLAP is bundled in the app (not On-Demand)."
  if [[ ${#present_clap[@]} -eq 0 ]]; then
    echo "#"
    echo "# No CLAP packages on this machine, so this overlay is a no-op."
    echo "targets: {}"
  else
    echo "targets:"
    for target in Tonearm TonearmMac; do
      echo "  $target:"
      echo "    sources:"
      for package in "${present_clap[@]}"; do
        echo "      - path: Resources/Models/$package"
        echo "        type: folder"
        echo "        buildPhase: resources"
      done
    done
  fi
} > "$BUNDLED_OVERLAY"

{
  echo "# GENERATED by scripts/generate-project.sh — do not edit, and do not"
  echo "# commit: it is written from which optional model packages are on THIS"
  echo "# machine. Only Demucs is On-Demand; a missing one is the honest"
  echo "# absence path (§36.5, FR-SEM-6): stem faders disabled."
  if [[ ${#present[@]} -eq 0 ]]; then
    echo "#"
    echo "# No optional model packages on this machine, so this overlay is a no-op."
    echo "targets: {}"
  else
    echo "targets:"
    echo "  Tonearm:"
    echo "    sources:"
    for entry in "${present[@]}"; do
      dir="${entry%%:*}"
      tag="${entry##*:}"
      echo "      - path: Resources/Models/$dir"
      echo "        type: folder"
      echo "        buildPhase: resources"
      echo "        resourceTags:"
      echo "          - $tag"
    done
  fi
} > "$OVERLAY"

if [[ ${#present_clap[@]} -gt 0 ]]; then
  echo "==> models: bundled in this project — ${present_clap[*]}"
fi
if [[ ${#missing_clap[@]} -gt 0 ]]; then
  echo "==> models: CLAP absent, so semantic search reports unavailable — ${missing_clap[*]}"
  echo "    Run 'make models' to fetch the packages pinned in Config/models.lock."
fi
if [[ ${#present[@]} -gt 0 ]]; then
  echo "==> models: optional ODR in this project — ${present[*]%%:*}"
fi
if [[ ${#absent[@]} -gt 0 ]]; then
  echo "==> models: optional absent, so their ODR tags are not in this project — ${absent[*]}"
fi

if [[ "${TONEARM_GENERATE_OVERLAYS_ONLY:-0}" == 1 ]]; then
  exit 0
fi

xcodegen generate
